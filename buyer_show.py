    ap.add_argument("--seed", type=int, help="随机种子,固定后可复现同一批场景")
    ap.add_argument("--type", default="自动判断",
                    help="首饰类型: 手链/项链/耳钉耳环/戒指/手镯/脚链/自动判断")
